def _safe_device_name(name):
    safe = re.sub(r'[^\w.-]+', '_', (name or '').strip()).strip('._')
    if not re.search(r'\.s\d+p$', safe, re.I):
        return None
    return safe[:80]


def validate_devices(model):
    """Check the project's S-parameter devices; returns enriched device
    list [{ref, pins, file, ts}] or raises ValidationError."""
    devices = model.get('devices') or []
    if not devices:
        return []
    ports = model.get('ports') or []
    port_nums = [int(p['number']) for p in ports]
    if len(set(port_nums)) != len(port_nums):
        raise ValidationError('duplicate port numbers')
    if any(n > 9 for n in port_nums):
        raise ValidationError('S-parameter devices require port numbers 1-9')
    exc = [int(p['number']) for p in ports if p.get('excite')]
    used = set()
    out = []
    for d in devices:
        ref = d.get('ref') or 'device'
        fname = _safe_device_name(d.get('file'))
        path = DEV_ROOT / (fname or '')
        if not fname or not path.is_file():
            raise ValidationError(f'{ref}: touchstone file "{d.get("file")}" not found on server')
        m = re.search(r'\.s(\d+)p$', fname, re.I)
        try:
            ts = parse_touchstone(path.read_text(), int(m.group(1)))
        except TouchstoneError as e:
            raise ValidationError(f'{ref}: bad touchstone file: {e}')
        pins = [int(x) for x in (d.get('pins') or [])]
        if len(pins) != ts['nports'] or len(set(pins)) != len(pins):
            raise ValidationError(
                f'{ref}: needs {ts["nports"]} distinct pin ports (got {pins})')
        for n in pins:
            if n not in port_nums:
                raise ValidationError(f'{ref}: pin port {n} does not exist')
            if n in used:
                raise ValidationError(f'{ref}: port {n} is used by another device')
            if n in exc:
                raise ValidationError(
                    f'{ref}: the excited port {n} cannot be a device pin')
            port = next(p for p in ports if int(p['number']) == n)
            if abs(float(port.get('impedance', 50)) - ts['r']) > ts['r'] * 0.01:
                raise ValidationError(
                    f'{ref}: port {n} impedance {port.get("impedance")} Ω must match '
                    f'the touchstone reference {ts["r"]} Ω')
        used |= set(pins)
        out.append({'ref': ref, 'pins': pins, 'file': fname, 'ts': ts})
    if len(used) >= len(port_nums):
        raise ValidationError('all ports are consumed by devices - none left to measure')
    return out


def _read_column(csv_path):
    """One excitation run's sparams.csv -> (freq list, {port: [complex]})."""
    lines = csv_path.read_text().strip().split('\n')
    header = lines[0].lstrip('#').split(',')
    freq = []
    cols = {}
    labels = []
    for ci in range(1, len(header) - 2, 2):
        num = int(header[ci][1])
        labels.append((ci, num))
        cols[num] = []
    for line in lines[1:]:
        v = [float(x) for x in line.split(',')]
        freq.append(v[0])
        for ci, num in labels:
            cols[num].append(complex(v[ci], v[ci + 1]))
    return freq, cols


def _write_touchstone(path, freq, mats, r=50.0):
    n = len(mats[0])
    out = [f'! generated by OpenEMS PCB Studio ({n}-port)', f'# GHz S RI R {r:g}']
    for k, f in enumerate(freq):
        row = [f'{f / 1e9:.6f}']
        for i in range(n):
            for j in range(n):
                a, b = (j, i) if n == 2 else (i, j)   # 2-port column order
                row.append(f'{mats[k][a][b].real:.6e} {mats[k][a][b].imag:.6e}')
        out.append(' '.join(row))
    path.write_text('\n'.join(out) + '\n')


def combine_devices(run_dir, model, stages, devices):
    """Assemble the full board S-matrix from the excitation runs, fold in
    every device, and rewrite sparams.csv for the external ports."""
    port_nums = sorted(int(p['number']) for p in model['ports'])
    n = len(port_nums)
    idx = {num: i for i, num in enumerate(port_nums)}
    freq = None
    columns = {}
    for st in stages:
        f, cols = _read_column(st['dir'] / 'sparams.csv')
        if freq is None:
            freq = f
        columns[st['exc']] = cols
    board = []
    for k in range(len(freq)):
        m = [[0j] * n for _ in range(n)]
        for jnum, cols in columns.items():
            for inum, vals in cols.items():
                m[idx[inum]][idx[jnum]] = vals[k]
        board.append(m)

    shutil.copy2(run_dir / 'sparams.csv', run_dir / 'sparams_board.csv')
    _write_touchstone(run_dir / f'board_full.s{n}p', freq, board)

    cur_nums = list(port_nums)
    mats = board
    for dev in devices:
        dmats, clamped = interpolate(dev['ts'], freq)
        pin_idx = [cur_nums.index(p) for p in dev['pins']]
        mats = [connect(mats[k], dmats[k], pin_idx) for k in range(len(freq))]
        cur_nums = [x for i, x in enumerate(cur_nums) if i not in pin_idx]

    exc = min(int(p['number']) for p in model['ports'] if p.get('excite'))
    e = cur_nums.index(exc)
    z0 = float(next(p for p in model['ports']
                    if int(p['number']) == exc).get('impedance', 50))
    if len(cur_nums) >= 2:
        _write_touchstone(run_dir / f'combined.s{len(cur_nums)}p', freq, mats)
    # excited-port column plus every port's own reflection S_ii (the full
    # matrix is available, so the GUI can show all external reflections)
    header = '#freq_Hz' + ''.join(f',S{i}{exc}_re,S{i}{exc}_im' for i in cur_nums)
    header += ''.join(f',S{i}{i}_re,S{i}{i}_im' for i in cur_nums if i != exc)
    header += ',Zin_re,Zin_im'
    lines = [header]
    for k, f in enumerate(freq):
        see = mats[k][e][e]
        den = 1 - see
        zin = z0 * (1 + see) / den if abs(den) > 1e-12 else complex(1e9, 0)
        row = [f'{f:e}']
        for i, num in enumerate(cur_nums):
            s = mats[k][i][e]
            row.append(f'{s.real:e},{s.imag:e}')
        for i, num in enumerate(cur_nums):
            if num == exc:
                continue
            s = mats[k][i][i]
            row.append(f'{s.real:e},{s.imag:e}')
        row.append(f'{zin.real:e},{zin.imag:e}')
        lines.append(','.join(row))
    (run_dir / 'sparams.csv').write_text('\n'.join(lines) + '\n')


def merge_excitations(run_dir, model, stages):
    """Merge the per-stage sparams.csv columns of a multi-excitation run
    (a user-selected subset of ports, no devices) into one sparams.csv:
    S_i,e for every excitation e, primary excitation's columns first."""
    freq = None
    parts = []                       # [(exc, {port: [complex]})] primary first
    for st in reversed(stages):      # root (primary) stage is last in stages
        f, cols = _read_column(st['dir'] / 'sparams.csv')
        if freq is None:
            freq = f
        parts.append((st['exc'], cols))
    # Zin of the primary excitation from the root csv (dropped by _read_column)
    root_lines = (run_dir / 'sparams.csv').read_text().strip().split('\n')
    zin = [line.split(',')[-2:] for line in root_lines[1:]]
    shutil.copy2(run_dir / 'sparams.csv', run_dir / 'sparams_primary.csv')
    header = '#freq_Hz'
    for exc, cols in parts:
        header += ''.join(f',S{i}{exc}_re,S{i}{exc}_im' for i in sorted(cols))
    header += ',Zin_re,Zin_im'
    lines = [header]
    for k, f in enumerate(freq):
        row = [f'{f:e}']
        for exc, cols in parts:
            for i in sorted(cols):
                v = cols[i][k]
                row.append(f'{v.real:e},{v.imag:e}')
        row.extend(zin[k])
        lines.append(','.join(row))
    (run_dir / 'sparams.csv').write_text('\n'.join(lines) + '\n')

MAX_LOG_LINES = 5000
# hard ceiling on excitations solved side by side. Each one is a full
# openEMS instance holding its own field arrays, so memory - not cores -
# is what bites first on a large board.
MAX_PARALLEL = 16

# How many cells one openEMS thread can usefully digest: below this the
# per-timestep barrier sync outweighs the extra worker. Measured here: a
# 70k-cell board ran fastest at 1 thread (2 threads were slower than
# sequential), 185k gained only 16% from a second thread, 1.5M peaked at
# 2-4 threads of 8. The rule matters most on many-core servers, where an
# even cores/parallel share alone would hand a medium board 16 threads.
CELLS_PER_THREAD = 150_000


def split_threads(cores, cells, parallel, live, queued):
    """openEMS threads for the next stage launch when several excitations
    share the machine. Left to itself each instance benchmarks thread
    counts at startup - a race: the first calibrates on an idle machine
    and grabs everything, the rest calibrate against that load and settle
    on 1 (a 4-way run was observed splitting 9/1/1/1). So when running
    side by side the split is computed here instead: an even share of the
    cores over the stages actually in flight (a stage launching beside
    fewer live runs gets the correspondingly larger share), capped at
    what the mesh size can put to work."""
    width = max(1, min(parallel, live + queued))
    fair = max(1, cores // width)
    useful = max(1, (cells or 0) // CELLS_PER_THREAD)
    return min(fair, useful)

