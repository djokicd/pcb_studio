@app.post('/api/mesh/profile')
def api_mesh_profile():
    """Lines one manual range would produce - the density-profile editor
    previews from the same code that meshes, so what is drawn is what is
    simulated."""
    p = request.get_json(force=True) or {}
    try:
        lo, hi = float(p.get('from') or 0.0), float(p.get('to') or 0.0)
        lo, hi = min(lo, hi), max(lo, hi)
        off = max(0.0, float(p.get('offset') or 0.0))
        # the line-free edge bands are mesh cells too: previewing them
        # keeps the reported smallest/largest cell honest
        off = min(off, (hi - lo) / 2.0 - 1e-6) if off > 0 else 0.0
        inner = (lo + off, hi - off) if off > 0 else (lo, hi)
        # the count may be given directly or as a target spacing - the
        # preview resolves it exactly as the mesher does
        cells = _range_cells(p, inner[1] - inner[0])
        lines = profile_lines(inner[0], inner[1], cells,
                              float(p.get('ratio') or 1.0),
                              str(p.get('bias') or 'uniform'))
    except (TypeError, ValueError) as e:
        return jsonify({'error': str(e)}), 400
    if off > 0 and lines:
        lines = [lo] + lines + [hi]
    widths = [b - a for a, b in zip(lines, lines[1:])]
    return jsonify({'lines': lines, 'band': off or None, 'cells': cells,
                    'minCell': round(min(widths), 6) if widths else None,
                    'maxCell': round(max(widths), 6) if widths else None})


def _safe_project_name(name):
    safe = re.sub(r'[^\w.-]+', '_', (name or '').strip()).strip('._')
    return safe[:60] or None


def _run_dir(run_id):
    """Resolve a results id: run_* under sims/, proj_<name>__run_* for a
    stored project run, and legacy proj_<name> for the old single copy."""
    if re.fullmatch(r'run_[0-9_]+', run_id):
        d = SIM_ROOT / run_id
        return d if d.is_dir() else None
    m = re.fullmatch(r'proj_([\w.-]+)__(run_[0-9_]+)', run_id)
    if m:
        d = PROJ_ROOT / m.group(1) / 'runs' / m.group(2)
        return d if d.is_dir() else None
    m = re.fullmatch(r'proj_([\w.-]+)', run_id)
    if m:
        d = PROJ_ROOT / m.group(1) / 'results'
        return d if d.is_dir() else None
    return None


def _project_runs(safe):
    """Stored runs of a project, newest first: [{runId, mtime, hasResults,
    stages, hasDesign, resultsId}], including the legacy single copy."""
    out = []
    pdir = PROJ_ROOT / safe
    for d in sorted((pdir / 'runs').glob('run_*'), reverse=True):
        if not d.is_dir():
            continue
        out.append({
            'runId': d.name,
            'mtime': d.stat().st_mtime,
            'hasResults': (d / 'sparams.csv').is_file(),
            'stages': 1 + sum(1 for _ in d.glob('exc_*/sparams.csv')),
            'hasDesign': (d / 'project.json').is_file(),
            'resultsId': f'proj_{safe}__{d.name}',
        })
    legacy = pdir / 'results'
    if (legacy / 'sparams.csv').is_file():
        out.append({
            'runId': None,
            'mtime': legacy.stat().st_mtime,
            'hasResults': True,
            'stages': 1 + sum(1 for _ in legacy.glob('exc_*/sparams.csv')),
            'hasDesign': (legacy / 'project.json').is_file(),
            'resultsId': f'proj_{safe}',
        })
    return out


def _read_probe(path):
    """openEMS probe file: comment lines then two whitespace-separated
    columns (time, value)."""
    t, v = [], []
    with open(path) as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith(('%', '#')):
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            try:
                t.append(float(parts[0]))
                v.append(float(parts[1]))
            except ValueError:
                continue
    return t, v


@app.get('/api/results/<run_id>/timedomain')
def api_timedomain(run_id):
    """Port voltage/current signals u(t), i(t) recorded by the ports -
    the full run duration, decimated to a plottable size. ?exc=<port>
    serves the signals of that excitation stage instead of the final
    one; the root response lists the stages that carry their own."""
    sim_dir = _dump_dir(run_id)
    if sim_dir is None:
        return jsonify({'error': 'bad run id'}), 400
    # lumped ports write port_ut{N}; MSL ports write port_ut{N}A/B/C probes
    # around the measurement plane (B sits on it) and port_it{N}A/B either
    # side of it (calcPort averages them)
    variants = {}
    for ut in sim_dir.glob('port_ut*'):
        m = re.fullmatch(r'port_ut_?(\d+)([ABC])?', ut.name)
        if m:
            variants.setdefault(int(m.group(1)), {})[m.group(2) or ''] = ut
    ports = []
    for n in sorted(variants):
        v = variants[n]
        ut = v.get('') or v.get('B') or v.get('A')
        if ut is None:
            continue
        t, u = _read_probe(ut)
        i_vals = []
        if '' in v:   # lumped port
            for it_name in (f'port_it_{n}', f'port_it{n}'):
                it_path = sim_dir / it_name
                if it_path.is_file():
                    i_vals = _read_probe(it_path)[1]
                    break
        else:         # MSL port: average the probes straddling the plane

            acc = []
            for sfx in ('A', 'B'):
                it_path = sim_dir / f'port_it{n}{sfx}'
                if it_path.is_file():
                    acc.append(_read_probe(it_path)[1])
            if acc:
                nmin = min(len(a) for a in acc)
                i_vals = [sum(a[k] for a in acc) / len(acc) for k in range(nmin)]
        ports.append({'n': n, 't': t, 'u': u, 'i': i_vals})
    if not ports:
        return jsonify({'error': 'no time-domain data for this run'}), 404
    # decimate to a plottable size on a common stride
    nmax = max(len(p['t']) for p in ports)
    stride = max(1, nmax // 4000)
    out = []
    for p in ports:
        out.append({
            'n': p['n'],
            't': p['t'][::stride],
            'u': p['u'][::stride],
            'i': p['i'][::stride],
        })
    excs = []
    if not request.args.get('exc'):
        excs = sorted(int(p.name[4:]) for p in sim_dir.glob('exc_*')
                      if p.name[4:].isdigit() and any(p.glob('port_ut*')))
    return jsonify({'ports': out, 'excs': excs})


