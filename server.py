class Runner:
    """Manages a single active simulation subprocess."""

    def __init__(self):
        self.lock = threading.Lock()
        self._reset()

    def _reset(self):
        self.run_id = None
        self.state = 'idle'      # idle|starting|running|post|done|error|stopped
        self.percent = 0.0
        self.log = []
        self.mesh_cells = None
        self.error = None
        self.proc = None
        self.started_at = None
        self.nrts = 1
        self.end_db = -40.0
        self.not_converged = False
        self.info = {}           # parsed engine facts (version, dt, ...)
        self.warn_msgs = []      # solver warnings, deduped
        self.stages = []
        # one record per excitation: each Octave run restarts its timestep
        # counter, so samples must not be concatenated. Records exist from
        # the start (state 'queued') so the run view can show the whole
        # plan, not just what has been launched.
        self.stage_data = []
        self.stage_idx = 0
        self.merge_only = False
        self.stage_info = ''
        self.devices = []
        self.base_model = None
        self.project = ''        # which design this run belongs to
        self.parallel = 1        # excitations solved side by side
        self.threads = 0         # openEMS threads per excitation (0 = auto)
        self.auto_split = False  # runner balances threads at each launch
        self.plan_cells = None   # mesh size known before launch
        self.procs = {}          # stage index -> live subprocess

    def _sync_progress_locked(self):
        """Overall progress: the mean over all stages, so every excitation
        contributes its own share whether it runs alone or beside others."""
        n = max(1, len(self.stage_data))
        self.percent = sum(s.get('percent', 0.0) for s in self.stage_data) / n

    def _stage(self):
        """Record of the excitation currently being solved (single-stage
        parsing helper; parallel readers address their record directly)."""
        if not self.stage_data:
            self.stage_data.append(self._new_stage_record(None, 'Run'))
        return self.stage_data[-1]

    @staticmethod
    def _new_stage_record(exc, label):
        return {'exc': exc, 'label': label, 'samples': [], 'info': {},
                'warn': [], 'notConverged': False, 'state': 'queued',
                'percent': 0.0, 'done': False, 'threads': None}

    def status(self, offset=0):
        with self.lock:
            offset = max(0, min(int(offset), len(self.log)))
            # the "current" stage for the single-stage top-level fields:
            # whichever is running (the earliest, when several are), else
            # the last one that produced anything
            cur = None
            for s in self.stage_data:
                if s.get('state') == 'running':
                    cur = s
                    break
            if cur is None and self.stage_data:
                cur = self.stage_data[-1]
            return {
                'runId': self.run_id,
                'state': self.state,
                'percent': round(self.percent, 1),
                'error': self.error,
                'lines': self.log[offset:],
                'nextOffset': len(self.log),
                'elapsed': round(time.time() - self.started_at, 1) if self.started_at else 0,
                # top level mirrors the stage in progress; `stages` carries
                # every excitation separately for the tabbed run view
                'samples': cur['samples'] if cur else [],
                'nrts': self.nrts,
                'endDb': self.end_db,
                'meshCells': self.mesh_cells,
                'notConverged': self.not_converged,
                'info': cur['info'] if cur else {},
                'warnMsgs': cur['warn'] if cur else [],
                'stageInfo': self.stage_info,
                'stageIdx': self.stage_data.index(cur) if cur in self.stage_data else 0,
                'stageCount': max(len(self.stages), len(self.stage_data)),
                'project': self.project,
                'parallel': self.parallel,
                'threads': self.threads,
                'running': sorted(self.procs),
                'stages': [{'exc': s['exc'], 'label': s['label'],
                            'samples': s['samples'], 'info': s['info'],
                            'warn': s['warn'], 'notConverged': s['notConverged'],
                            'state': s.get('state', 'queued'),
                            'percent': round(s.get('percent', 0.0), 1),
                            'threads': s.get('threads')}
                           for s in self.stage_data],
            }

    def start(self, model):
        with self.lock:
            if any(p.poll() is None for p in self.procs.values()):
                raise RuntimeError('A simulation is already running')
            devices = validate_devices(model)   # raises ValidationError
            run_id = time.strftime('run_%Y%m%d_%H%M%S')
            sim_dir = SIM_ROOT / run_id
            # nothing is written until every stage has validated - a
            # rejected run must not leave an empty run directory behind

            # with S-parameter devices (or the full-S-matrix option) one
            # excitation run per port is needed; the user's excited port
            # runs last in the run root. Every stage keeps the configured
            # field dumps, so the current density can be reviewed for each
            # excitation - not only the primary one.
            full_s = bool((model.get('sim') or {}).get('fullS')) \
                and len(model.get('ports') or []) > 1
            excited = sorted(int(p['number']) for p in (model.get('ports') or [])
                             if p.get('excite'))
            if not excited:
                raise ValidationError('No excited port - mark at least one '
                                      'port as the excitation source')

            def stage_model(n):
                m2 = json.loads(json.dumps(model))
                for q in m2['ports']:
                    q['excite'] = (int(q['number']) == n)
                return m2

            # stage list; the primary excitation runs last in the run root
            stages = []
            exc = excited[0]
            if devices or full_s:
                # devices / full S-matrix: one excitation run per port
                sweep = sorted(int(p['number']) for p in model['ports'])
            elif len(excited) > 1:
                # user-selected subset of excitations
                sweep = excited
            else:
                sweep = [exc]
            for n in sweep:
                if n == exc:
                    continue
                stages.append({'dir': sim_dir / f'exc_{n}',
                               'model': stage_model(n), 'exc': n})
            stages.append({'dir': sim_dir, 'model': stage_model(exc),
                           'exc': exc if len(sweep) > 1 else None})
            merge_only = not (devices or full_s) and len(sweep) > 1

            # how many excitations to solve side by side. They are wholly
            # independent runs writing to separate directories, so the only
            # shared resources are cores and memory: the thread budget is
            # split between them, and the user is told the memory multiplies.
            sim_cfg = model.get('sim') or {}
            par = sim_cfg.get('parallel')
            try:
                par = int(par) if par else 1
            except (TypeError, ValueError):
                par = 1
            if par <= 0:                       # 'auto'
                par = max(1, (os.cpu_count() or 1) // 2)
            par = max(1, min(par, len(stages), MAX_PARALLEL))
            # Threads: a SINGLE run is left to openEMS, which benchmarks
            # the actual mesh at startup and picks its own count - that
            # beats anything computed here. Side-by-side runs must NOT be
            # left to it: the startup benchmarks race (the first instance
            # calibrates on an idle machine and grabs every core, the
            # rest calibrate against that load and settle on 1 - observed
            # as a 9/1/1/1 split on a 4-way run), so the runner assigns
            # an even share per launch instead (split_threads). Small
            # meshes get 1 thread each: openEMS gains nothing from more
            # there, and forcing cores/N on the bundled amplifier made a
            # 4-excitation run take 42 s against 17.5 s at 1 thread each.
            # An explicit threadsPerExc overrides all of this.
            threads = sim_cfg.get('threadsPerExc')
            try:
                threads = max(0, int(threads)) if threads else 0
            except (TypeError, ValueError):
                threads = 0

            # validate every stage before anything runs
            for st in stages:
                if threads:
                    st['model'].setdefault('sim', {})['numThreads'] = threads
                st['script'] = generate_script(st['model'])
            # every excitation shares the board geometry, hence the mesh
            plan_cells = build_mesh(model).get('cells')

            self._reset()
            self.run_id = run_id
            self.state = 'starting'
            self.started_at = time.time()
            self.devices = devices
            self.base_model = model
            self.stages = stages
            self.stage_idx = 0
            self.merge_only = merge_only
            self.project = str(model.get('name') or '')
            self.parallel = par
            self.threads = threads
            self.auto_split = threads == 0 and par > 1
            self.plan_cells = plan_cells
            multi = len(stages) > 1
            for i, st in enumerate(stages):
                self.stage_data.append(self._new_stage_record(
                    st.get('exc'),
                    (f'Exc {st["exc"]}' if multi and st.get('exc') is not None
                     else f'Run {i + 1}' if multi else 'Run')))
            # persist the exact model that produced this run: the run stays
            # self-describing and recoverable with no browser involved
            sim_dir.mkdir(parents=True, exist_ok=True)
            (sim_dir / 'project.json').write_text(json.dumps(model, indent=1))
            sim = model.get('sim') or {}
            self.nrts = max(1, int(sim.get('maxTimesteps') or 30000))
            self.end_db = float(sim.get('endCriteria') or -40.0)
            self._pump_locked()
        return run_id

    def _pump_locked(self):
        """Keep `parallel` excitations in flight, launching queued ones as
        slots free up."""
        for idx, rec in enumerate(self.stage_data):
            if len(self.procs) >= self.parallel:
                break
            if rec['state'] != 'queued':
                continue
            try:
                self._launch_stage_locked(idx)
            except Exception as e:
                rec['state'] = 'error'
                self.state = 'error'
                self.error = f'failed to start excitation {idx + 1}: {e}'
                return
        self._update_stage_info_locked()

    def _update_stage_info_locked(self):
        n = len(self.stage_data)
        if n <= 1:
            self.stage_info = ''
            return
        done = sum(1 for s in self.stage_data if s['state'] in ('done', 'error'))
        live = len(self.procs)
        self.stage_info = f'{done}/{n} excitations'
        if live > 1:
            self.stage_info += f' · {live} running in parallel'
            tl = sorted({self.stage_data[i].get('threads') for i in self.procs}
                        - {None})
            if tl:
                self.stage_info += (
                    f' · {tl[0]} thread{"s" if tl[0] != 1 else ""} each'
                    if len(tl) == 1
                    else f' · {"/".join(map(str, tl))} threads')

    def _launch_stage_locked(self, idx):
        st = self.stages[idx]
        rec = self.stage_data[idx]
        st['dir'].mkdir(parents=True, exist_ok=True)
        script = st['script']
        if self.auto_split:
            queued = sum(1 for r in self.stage_data
                         if r['state'] == 'queued')      # includes this one
            t = split_threads(os.cpu_count() or 1, self.plan_cells,
                              self.parallel, len(self.procs), queued)
            # the validated script carries no thread flag; the launch pins
            # this stage's fair share (a lone tail stage gets them all)
            script = script.replace(
                'RunOpenEMS(Sim_Path, Sim_File);',
                f"RunOpenEMS(Sim_Path, Sim_File, '--numThreads={t}');")
            rec['threads'] = t
        (st['dir'] / 'pcb_sim.m').write_text(script)
        rec['state'] = 'running'
        proc = subprocess.Popen(
            ['stdbuf', '-oL', '-eL', 'octave', '--no-gui', '--no-window-system', 'pcb_sim.m'],
            cwd=st['dir'],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            start_new_session=True,
        )
        self.procs[idx] = proc
        self.proc = proc          # kept for "is anything running" checks
        threading.Thread(target=self._reader, args=(proc, idx), daemon=True).start()

    def stop(self):
        with self.lock:
            procs = [p for p in self.procs.values() if p.poll() is None]
            if not procs:
                return False
            self.state = 'stopped'
        for proc in procs:
            try:
                os.killpg(os.getpgid(proc.pid), signal.SIGTERM)
            except (ProcessLookupError, PermissionError):
                pass
        for proc in procs:
            try:
                for _ in range(20):
                    if proc.poll() is not None:
                        break
                    time.sleep(0.25)
                if proc.poll() is None:
                    os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
            except (ProcessLookupError, PermissionError):
                pass
        return True

    # ---- internal ------------------------------------------------------
    def _append_line(self, line, rec=None):
        line = line.rstrip()
        if not line:
            return
        # with several solvers talking at once the shared log needs to say
        # who is speaking, or the interleaving is unreadable
        tag = ''
        if rec is not None and len(self.procs) > 1:
            tag = f'[{rec["label"]}] '
        self.log.append(tag + line)
        if len(self.log) > MAX_LOG_LINES:
            del self.log[:len(self.log) - MAX_LOG_LINES]
        self._parse(line, rec)

